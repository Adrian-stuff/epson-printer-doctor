"""Regenerate extra_models.py from data/devices.xml (ez-reset's device list).

Converts every Epson L-series model found in devices.xml with the upstream
parse_devices.py converter, and writes the result as a plain Python dict so
it can be read and audited before use.

    .venv/bin/python build_models.py
"""
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).parent
XML = HERE / "data" / "devices.xml"
OUT = HERE / "extra_models.py"

models = sorted(set(re.findall(r"\bL[1-6]\d{3}\b", XML.read_text(errors="ignore"))))
merged = {}
for m in models:
    if any(m in v.get("alias", []) for v in merged.values()):
        continue  # already covered as an alias of an earlier model
    r = subprocess.run(
        [sys.executable, str(HERE / "parse_devices.py"), "-c", str(XML), "-e", "-m", m],
        capture_output=True, text=True, cwd=HERE,
    )
    if "PRINTER_CONFIG" not in r.stdout:
        print(f"{m}: no usable definition, skipped")
        continue
    ns = {"range": range}
    exec(r.stdout, ns)  # output of our own converter: a dict literal
    for name, conf in ns["PRINTER_CONFIG"].items():
        if name not in merged:
            merged[name] = conf
            print(f"{m}: {name} ok" + (f" (aliases {', '.join(conf['alias'])})" if conf.get("alias") else ""))


# Structured fatal error log: upstream flattens the registers into one list,
# losing which bytes form one code. Keep the groups (name, kind, registers).
import xml.etree.ElementTree as ET

root = ET.parse(XML).getroot()


def fatal_log(model):
    for printer in root.iterfind(".//printer"):
        if not re.search(rf"\b{model}\b", printer.attrib.get("title", "")):
            continue
        groups = []
        for spec in printer.attrib["specs"].split(","):
            for elm in root.iterfind(".//" + spec):
                for fat in elm.iterfind("./information/report/fatals"):
                    regs = [int(x, 16) for x in (fat.findtext("registers") or "").split()]
                    if regs:
                        groups.append({
                            "name": (fat.findtext("name") or "").replace("% ", "#"),
                            "kind": (fat.findtext("filter") or "PRINTER").lower(),
                            "registers": regs,
                        })
        if groups:
            return groups
    return None


for name, conf in merged.items():
    log = fatal_log(name)
    if log:
        conf["fatal_log"] = log

with OUT.open("w") as f:
    f.write('"""Generated by build_models.py from data/devices.xml. Do not edit."""\n\n')
    f.write("EXTRA_PRINTER_CONFIG = {\n")
    for name in sorted(merged):
        f.write(f"    {name!r}: {merged[name]!r},\n")
    f.write("}\n")
print(f"\nWrote {len(merged)} model definitions to {OUT.name}")
